/**
 * scripts/generate-guide-pdf.mjs
 *
 * Produces the canonical Protein Guide PDF — the authoritative save/print
 * artifact for manuscript v1.2.
 *
 * WHY THIS IS AN AUTHORING STEP AND NOT A BUILD STEP
 * Gmail's native print does not preserve the Guide's print stylesheet, so the
 * eight-page pagination cannot be guaranteed through any recipient's client.
 * The fix is to stop depending on their renderer: this script paginates the
 * document once, here, under a browser we control, and the result is committed
 * as a fixed-layout asset. Every recipient then opens the same eight pages
 * regardless of their client, browser, printer or CSS support.
 *
 * It is deliberately NOT wired into `npm run build`. Vercel's build image has
 * no Chrome, and a build that silently produced a different PDF would defeat
 * the point of a canonical artifact. The PDF is regenerated by hand when the
 * approved manuscript or its presentation changes, and `proteinGuidePdf.test.mjs`
 * fails the suite if the committed PDF no longer matches the current renderer.
 *
 *   node --import ./scripts/_resolve-ts.mjs scripts/generate-guide-pdf.mjs
 *
 * Set CHROME_PATH to override browser discovery.
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const PDF_PATH      = join(ROOT, 'public', 'guides', 'myoguard-protein-guide-v1.2.pdf');
const MANIFEST_PATH = join(ROOT, 'src', 'lib', 'guide', 'proteinGuidePdf.manifest.json');
const EXPECTED_PAGES = 8;

const CANDIDATES = [
  process.env.CHROME_PATH,
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].filter(Boolean);

function findBrowser() {
  const hit = CANDIDATES.find(p => existsSync(p));
  if (!hit) {
    throw new Error(
      'No Chrome/Edge binary found. Set CHROME_PATH to a Chromium-based browser.',
    );
  }
  return hit;
}

/** Counts page objects in the PDF. The trailing [^s] excludes /Pages nodes. */
function countPages(bytes) {
  return (bytes.toString('latin1').match(/\/Type\s*\/Page[^s]/g) || []).length;
}

async function main() {
  const { renderProteinGuideHtml } = await import(
    pathToFileURL(join(ROOT, 'src/lib/guide/renderProteinGuide.ts')).href
  );
  const { GUIDE_MANUSCRIPT_VERSION } = await import(
    pathToFileURL(join(ROOT, 'src/lib/guide/proteinGuideContent.ts')).href
  );
  const { canonicalPdfSourceHtml } = await import(
    pathToFileURL(join(ROOT, 'src/lib/guide/proteinGuidePdf.ts')).href
  );

  // The PDF is generated from the delivered email body itself — not from a
  // second, parallel template. There is therefore no way for the printed
  // artifact and the emailed document to carry different clinical text.
  const html = renderProteinGuideHtml();
  // Signature over the printed document, not the emailed one — see
  // canonicalPdfSourceHtml for why the action block is excluded.
  const htmlSha256 = createHash('sha256')
    .update(canonicalPdfSourceHtml(html), 'utf8')
    .digest('hex');

  const tmpDir = join(ROOT, 'node_modules', '.cache', 'guide-pdf');
  mkdirSync(tmpDir, { recursive: true });
  const tmpHtml = join(tmpDir, 'guide.html');
  writeFileSync(tmpHtml, html, 'utf8');

  mkdirSync(dirname(PDF_PATH), { recursive: true });

  const browser = findBrowser();
  execFileSync(
    browser,
    [
      '--headless',
      '--disable-gpu',
      '--no-sandbox',
      '--no-pdf-header-footer',
      `--print-to-pdf=${PDF_PATH}`,
      pathToFileURL(tmpHtml).href,
    ],
    { stdio: 'ignore' },
  );
  rmSync(tmpDir, { recursive: true, force: true });

  const bytes = readFileSync(PDF_PATH);
  const pages = countPages(bytes);
  if (pages !== EXPECTED_PAGES) {
    throw new Error(
      `Refusing to publish: the Guide paginated to ${pages} pages, not ${EXPECTED_PAGES}. ` +
        'The canonical artifact must be exactly the eight approved manuscript pages.',
    );
  }

  writeFileSync(
    MANIFEST_PATH,
    JSON.stringify(
      {
        templateId: 'service.protein_guide.v1_2',
        version: GUIDE_MANUSCRIPT_VERSION,
        pages,
        // Binds the committed PDF to the exact document it was printed from.
        // If the renderer or the approved content changes, this stops matching
        // and the suite fails until the PDF is regenerated.
        htmlSha256,
        pdfSha256: createHash('sha256').update(bytes).digest('hex'),
        pdfBytes: bytes.length,
      },
      null,
      2,
    ) + '\n',
    'utf8',
  );

  console.log(`canonical PDF written: ${pages} pages, ${bytes.length} bytes`);
  console.log(`bound to rendered HTML sha256 ${htmlSha256.slice(0, 16)}…`);
}

main().catch(err => {
  console.error(err.message);
  process.exit(1);
});
